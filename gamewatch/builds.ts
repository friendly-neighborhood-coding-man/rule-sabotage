/**
 * GameWatch build materializer (EXPERIMENTAL, QA demonstration only).
 *
 * Makes a separate copy of the V6 game code under server/v6-build-<label>/ (a sibling of server/v6/, so every relative
 * import resolves exactly as in the original) and applies the source changes listed for that build in a manifest.
 * The normal playable game (server/v6/) is never modified. Generated copies are git-ignored and rebuilt on demand.
 *
 * Each change is an exact text replacement that must match exactly once, so a build is reproducible from
 * (baseline file hash, change list). A build with no changes is a byte-identical copy of the baseline.
 */
import { readFileSync, writeFileSync, mkdirSync, rmSync, readdirSync, statSync, existsSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { createHash } from 'node:crypto';
import { fileURLToPath } from 'node:url';

export const ROOT = fileURLToPath(new URL('..', import.meta.url));
const SRC = join(ROOT, 'server/v6');
const sha = (s: string | Buffer) => createHash('sha256').update(s).digest('hex');

export type Change = { id: string; file: string; find: string; replace: string };
export type BuildInfo = { label: string; dir: string; changes: string[]; files: Record<string, string> };

function copyTree(from: string, to: string) {
  mkdirSync(to, { recursive: true });
  for (const n of readdirSync(from)) {
    const a = join(from, n), b = join(to, n);
    if (statSync(a).isDirectory()) copyTree(a, b); else if (n.endsWith('.ts')) writeFileSync(b, readFileSync(a));
  }
}

/** Materialize one build. `changes` are applied in order; each must match its file exactly once. */
export function materialize(label: string, changes: Change[]): BuildInfo {
  if (!/^[A-Za-z0-9-]+$/.test(label)) throw new Error(`bad build label ${label}`);
  const dir = join(ROOT, 'server', `v6-build-${label}`);
  rmSync(dir, { recursive: true, force: true });
  copyTree(SRC, dir);
  for (const c of changes) {
    if (!c.file.startsWith('server/v6/')) throw new Error(`change ${c.id}: only server/v6/ files can be changed`);
    const f = join(dir, c.file.slice('server/v6/'.length));
    const text = readFileSync(f, 'utf8').replace(/\r\n/g, '\n');
    const n = text.split(c.find).length - 1;
    if (n !== 1) throw new Error(`change ${c.id}: expected exactly 1 match in ${c.file}, found ${n}`);
    writeFileSync(f, text.replace(c.find, c.replace));
  }
  const files: Record<string, string> = {};
  for (const n of ['engine.ts', 'turn.ts', 'forks/trial.ts', 'forks/tiers.ts']) files[n] = sha(readFileSync(join(dir, n), 'utf8').replace(/\r\n/g, '\n')).slice(0, 16);
  writeFileSync(join(dir, 'BUILD.txt'), `Generated by gamewatch/builds.ts. Not part of the playable game. Do not edit.\n`);
  return { label, dir, changes: changes.map(c => c.id), files };
}

/** Load the modules of a materialized build. */
export async function loadBuild(label: string) {
  const dir = join(ROOT, 'server', `v6-build-${label}`);
  if (!existsSync(dir)) throw new Error(`build ${label} not materialized`);
  const u = (f: string) => new URL(`file://${join(dir, f)}`).href;
  const engine = await import(u('engine.ts')) as typeof import('../server/v6/engine.ts');
  const turn = await import(u('turn.ts')) as typeof import('../server/v6/turn.ts');
  const selfplay = await import(u('selfplay.ts')) as typeof import('../server/v6/selfplay.ts');
  return { engine, turn, selfplay, dir };
}

export const baselineEngineHash = () => sha(readFileSync(join(SRC, 'engine.ts'), 'utf8').replace(/\r\n/g, '\n')).slice(0, 16);
export { dirname };
